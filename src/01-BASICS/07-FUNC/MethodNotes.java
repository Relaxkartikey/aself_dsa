/*
==================================================
              FUNCTIONS / METHODS
==================================================


1. WHAT IS A METHOD?
--------------------------------------------------

A method is a reusable block of code that performs
a specific task.

Example:

void sayHello() {
    System.out.println("Hello");
}


2. WHY USE METHODS?
--------------------------------------------------

Methods help us:

- Reuse code
- Avoid repetition
- Organize code
- Make programs easier to understand
- Make debugging easier


3. BASIC STRUCTURE
--------------------------------------------------

returnType methodName(parameters) {
    // code
}


Example:

void sayHello() {
    System.out.println("Hello");
}


4. METHOD DEFINITION
--------------------------------------------------

Writing the method is called defining/creating
the method.

Example:

void sayHello() {
    System.out.println("Hello");
}


5. METHOD CALL
--------------------------------------------------

A method does NOT execute just because we define it.

We have to call it.

Example:

sayHello();


6. DEFINITION vs CALL
--------------------------------------------------

Definition:

void sayHello() {
    System.out.println("Hello");
}


Call:

sayHello();


Think:

Definition = Create the machine
Call       = Use the machine


7. SIMPLE EXAMPLE
--------------------------------------------------

void sayHello() {
    System.out.println("Hello");
}

void main() {

    sayHello();

}


Output:

Hello


8. IMPORTANT TERMS
--------------------------------------------------

returnType
    → What the method gives back

methodName
    → Name used to call the method

parameters
    → Input given to the method

method body
    → Code inside { }


We will learn parameters and return values later.


==================================================
*/