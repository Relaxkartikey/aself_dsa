void main() {

    /*
For Loop

Syntax:

for(initialization; condition; update){
    // Code
}

Parts:
1. Initialization -> Runs once
2. Condition -> Checked before every iteration
3. Update -> Runs after every iteration

Note:
- Best when the number of iterations is known.
*/

    for(int i=1;i<=10;i++) {
        System.out.print(i + ", ");
    }


}