void main() {



    /*
Unary Operators

+   Unary Plus
-   Unary Minus
++  Increment
--  Decrement

Types:
++a : Pre Increment (Increment → Use)
a++ : Post Increment (Use → Increment)

--a : Pre Decrement
a-- : Post Decrement
*/


    int a = 10;

    System.out.println("Initial Value : " + a);

    System.out.println((a++));
    System.out.println(a);

    System.out.println((++a));
    System.out.println(a);

    System.out.println((a--));
    System.out.println(a);

    System.out.println((--a));
    System.out.println(a);



}