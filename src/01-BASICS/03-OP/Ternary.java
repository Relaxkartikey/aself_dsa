void main() {


    /*
Ternary Operator

Syntax:
condition ? trueValue : falseValue;

Shortcut for simple if-else.

Best For:
- Assigning values
- Simple conditions
- Cleaner code
*/

    int age = 20;

    String result = (age >= 18) ? "Eligible" : "Not Eligible";
    // Syntax:
    //condition ? trueValue : falseValue;

    System.out.println(result);

}