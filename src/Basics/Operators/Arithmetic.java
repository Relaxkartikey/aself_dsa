void main() {

    /*
Arithmetic Operators

+  Addition
-  Subtraction
*  Multiplication
/  Division
%  Modulus (Remainder)

Note:
- Integer / Integer = Integer
- Decimal / Integer = Decimal
- % returns the remainder
*/

    System.out.println(4 + 3);
    System.out.println(4 - 3);
    System.out.println(4 * 3);
    System.out.println(4 / 2);
    System.out.println(4 % 3);
    System.out.println(4 % 2);
    System.out.println(4 / 2.0);
}